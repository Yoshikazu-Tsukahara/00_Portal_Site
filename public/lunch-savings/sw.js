/* ランチ貯金専用 Service Worker（scope: /lunch-savings） */
const CACHE_NAME = "lunch-savings-v2";
const PRECACHE = [
  "/lunch-savings",
  "/lunch-savings.webmanifest",
  "/icons/lunch-savings-192.png",
  "/icons/lunch-savings-512.png",
];

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(CACHE_NAME)
      .then((cache) => cache.addAll(PRECACHE))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((key) => key !== CACHE_NAME)
            .map((key) => caches.delete(key)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const { request } = event;
  if (request.method !== "GET") return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  // この SW の対象は /lunch-savings 配下とアイコン・manifest のみ
  const path = url.pathname;
  const inScope =
    path === "/lunch-savings" ||
    path.startsWith("/lunch-savings/") ||
    path === "/lunch-savings.webmanifest" ||
    path.startsWith("/icons/lunch-savings");
  if (!inScope) return;

  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request)
        .then((response) => {
          const copy = response.clone();
          void caches.open(CACHE_NAME).then((cache) => cache.put(request, copy));
          return response;
        })
        .catch(() =>
          caches
            .match(request)
            .then((cached) => cached || caches.match("/lunch-savings")),
        ),
    );
    return;
  }

  event.respondWith(
    caches.match(request).then((cached) => {
      if (cached) return cached;
      return fetch(request).then((response) => {
        if (response.ok) {
          const copy = response.clone();
          void caches.open(CACHE_NAME).then((cache) => cache.put(request, copy));
        }
        return response;
      });
    }),
  );
});
