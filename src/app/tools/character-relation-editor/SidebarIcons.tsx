import type { ReactNode } from "react";

/** サイドバー用コンパクトアイコンボタン */
export function SidebarIconButton({
  label,
  onClick,
  active = false,
  danger = false,
  children,
}: {
  label: string;
  onClick: () => void;
  active?: boolean;
  danger?: boolean;
  children: ReactNode;
}) {
  return (
    <button
      type="button"
      title={label}
      aria-label={label}
      onClick={onClick}
      className={`flex size-6 items-center justify-center rounded-md transition-colors ${
        active
          ? "bg-[var(--accent)] text-zinc-900"
          : danger
            ? "text-zinc-400 hover:bg-white hover:text-rose-600"
            : "text-zinc-400 hover:bg-white hover:text-zinc-700"
      }`}
    >
      {children}
    </button>
  );
}

